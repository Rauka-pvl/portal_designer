IMPORTANT_FILL = {
    "Обязательно": "FECACA",
    "Желательно": "FED7AA",
    "Можно позже": "E5E7EB",
}

RESULT_OPTIONS = '"Не проверял,Работает,Не работает,Непонятно"'


def style_header(ws):
    fill = PatternFill("solid", fgColor="1F2937")
    font = Font(bold=True, color="FFFFFF", name="Calibri", size=11)
    for col in range(1, len(HEADERS) + 1):
        cell = ws.cell(1, col)
        cell.fill = fill
        cell.font = font
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    ws.row_dimensions[1].height = 32
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(HEADERS))}{1}"


def fill_sheet(ws, rows, title):
    ws.title = title
    thin = Border(
        left=Side(style="thin", color="D1D5DB"),
        right=Side(style="thin", color="D1D5DB"),
        top=Side(style="thin", color="D1D5DB"),
        bottom=Side(style="thin", color="D1D5DB"),
    )
    for i, h in enumerate(HEADERS, 1):
        ws.cell(1, i, h)
    style_header(ws)

    for idx, (section, what, how, important) in enumerate(rows, 1):
        values = [idx, section, what, how, important, "Не проверял", None, "", ""]
        for col, val in enumerate(values, 1):
            cell = ws.cell(idx + 1, col, val)
            cell.border = thin
            cell.alignment = Alignment(vertical="center", wrap_text=True)
            if col == 1:
                cell.alignment = Alignment(horizontal="center", vertical="center")
            if col == 5 and important in IMPORTANT_FILL:
                cell.fill = PatternFill("solid", fgColor=IMPORTANT_FILL[important])
                cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            if col == 6:
                cell.alignment = Alignment(horizontal="center", vertical="center")
            if col == 7:
                cell.number_format = "YYYY-MM-DD"
        ws.row_dimensions[idx + 1].height = 48

    widths = [5, 18, 34, 62, 12, 14, 14, 16, 28]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

    dv = DataValidation(type="list", formula1=RESULT_OPTIONS, allow_blank=True)
    ws.add_data_validation(dv)
    dv.add(f"F2:F{len(rows) + 1}")

    last = len(rows) + 1
    r = last + 2
    ws.cell(r, 1, "Всего пунктов").font = Font(bold=True)
    ws.cell(r, 2, f"=COUNTA(C2:C{last})")
    ws.cell(r + 1, 1, "Работает")
    ws.cell(r + 1, 2, f'=COUNTIF(F2:F{last},"Работает")')
    ws.cell(r + 2, 1, "Не работает")
    ws.cell(r + 2, 2, f'=COUNTIF(F2:F{last},"Не работает")')
    ws.cell(r + 3, 1, "Ещё не проверяли")
    ws.cell(r + 3, 2, f'=COUNTIF(F2:F{last},"Не проверял")')
    ws.cell(r + 4, 1, "Дата файла")
    ws.cell(r + 4, 2, TODAY.isoformat())


